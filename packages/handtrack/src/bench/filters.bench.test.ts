// The benchmark behind the claim.
//
// "Better tracking" is easy to assert and hard to believe, so these tests pin
// it to numbers. They run in CI on synthetic traces, so they need no camera, no
// permission prompt and no device, and they fail if a change makes the tracking
// worse — which is the only way a claim like this stays true over time.
//
// `npm run bench` re-runs them and writes the measured table to
// `packages/handtrack/BENCHMARK.md`, which is where the numbers quoted in the
// README and on the site come from. Nothing is copied by hand.

import fs from 'node:fs';
import path from 'node:path';
import { OneEuroPoint } from '../oneEuro';
import { FistGate } from '../fist';
import { SlotAssigner } from '../slots';
import { LegacyEma, LEGACY_CUTOFF_HZ } from './legacy';
import { stillTrace, sineTrace, sineTruth, stepTrace, mulberry32, gaussian } from './traces';
import { rmsJitter, lagMs, settlingMs, countFlips, runFilter } from './metrics';
import type { Point } from '../types';

const HZ = 30;
const SAMPLE_MS = 1000 / HZ;

const report: string[] = [];
const note = (line: string) => report.push(line);

afterAll(() => {
  if (!process.env.BENCH_REPORT) return;
  const out = [
    '# Benchmark results',
    '',
    'Generated by `npm run bench`. Do not edit by hand.',
    '',
    'Synthetic traces at 30 Hz sampling, the rate hand inference actually runs at.',
    'Distances are in units of the viewport (1.0 = full width), so "x1000" is',
    'roughly tenths of a percent of the screen.',
    '',
    '```',
    ...report,
    '```',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(process.cwd(), 'packages/handtrack/BENCHMARK.md'), out);
});

const oneEuroRun = (trace: ReturnType<typeof stillTrace>) => {
  const f = new OneEuroPoint();
  return runFilter(trace, (s, dt) => f.filter(s.x, s.y, dt));
};
const legacyRun = (trace: ReturnType<typeof stillTrace>) => {
  const f = new LegacyEma();
  return runFilter(trace, (s, dt) => f.filter(s.x, s.y, dt));
};

describe('one euro vs the fixed EMA it replaced', () => {
  // The heart of it. A fixed-cutoff filter trades jitter against lag along a
  // single axis: any setting steadier at rest is also laggier in motion. One
  // Euro is not on that line, so it should beat the same baseline on *both* at
  // once. If it ever wins only one, the defaults have collapsed into being a
  // plain low-pass and the whole advantage is gone.

  const stillOpts = { ms: 3000, hz: HZ, noise: 0.004, seed: 7 };
  const sineOpts = { ms: 4000, hz: HZ, noise: 0.004, seed: 11, freqHz: 0.5, amplitude: 0.17 };

  const still = stillTrace({ x: 0.5, y: 0.5 }, stillOpts);
  const sine = sineTrace(sineOpts);
  const truth = sineTruth(sineOpts);

  const rawJitter = rmsJitter(still);
  const oeJitter = rmsJitter(oneEuroRun(still));
  const emaJitter = rmsJitter(legacyRun(still));

  const oeLag = lagMs(oneEuroRun(sine), truth, SAMPLE_MS);
  const emaLag = lagMs(legacyRun(sine), truth, SAMPLE_MS);

  it('is steadier than the EMA on a hand held still', () => {
    note(`legacy EMA cutoff        ${LEGACY_CUTOFF_HZ.toFixed(2)} Hz (fixed)`);
    note(`jitter, raw input        ${(rawJitter * 1000).toFixed(2)} (x1000 of viewport)`);
    note(`jitter, legacy EMA       ${(emaJitter * 1000).toFixed(2)}`);
    note(`jitter, one euro         ${(oeJitter * 1000).toFixed(2)}`);
    expect(oeJitter).toBeLessThan(emaJitter);
  });

  it('removes most of the raw noise', () => {
    expect(oeJitter).toBeLessThan(rawJitter * 0.5);
  });

  it('lags less than the EMA on a moving hand', () => {
    note(`lag, legacy EMA          ${emaLag.toFixed(1)} ms`);
    note(`lag, one euro            ${oeLag.toFixed(1)} ms`);
    expect(oeLag).toBeLessThan(emaLag);
  });

  it('wins on jitter and lag simultaneously, which a fixed cutoff cannot', () => {
    // Restated as one assertion because this is the claim, and it should fail
    // loudly and by name if it ever stops holding.
    expect(oeJitter).toBeLessThan(emaJitter);
    expect(oeLag).toBeLessThan(emaLag);
  });

  it('settles a step at least as fast as the EMA', () => {
    const stepOpts = { ms: 2500, hz: HZ, noise: 0.002, seed: 3, atMs: 500 };
    const from = { x: 0.3, y: 0.5 };
    const to = { x: 0.7, y: 0.5 };
    const trace = stepTrace(from, to, stepOpts);
    const oe = settlingMs(oneEuroRun(trace), to, 500, 0.012);
    const ema = settlingMs(legacyRun(trace), to, 500, 0.012);
    note(`step settling, legacy    ${ema.toFixed(0)} ms`);
    note(`step settling, one euro  ${oe.toFixed(0)} ms`);
    expect(oe).toBeLessThanOrEqual(ema);
  });
});

describe('fist gate vs a bare threshold', () => {
  // A hand resting at the detection boundary is the failure this fixes. With a
  // single threshold the state oscillates, and because a fist locks the chord,
  // the oscillation is audible.
  const NAIVE_THRESHOLD = 0.7;

  function boundaryCurls(seed = 5, n = 200, noise = 0.06): number[] {
    const rng = mulberry32(seed);
    // Curl parked exactly on the naive threshold, with realistic noise.
    return Array.from({ length: n }, () => NAIVE_THRESHOLD + gaussian(rng) * noise);
  }

  it('does not chatter while a hand rests on the threshold', () => {
    const curls = boundaryCurls();
    const naive = curls.map(c => c >= NAIVE_THRESHOLD);
    const gate = new FistGate();
    const gated = curls.map((c, i) => gate.update(c, i * SAMPLE_MS));

    const naiveFlips = countFlips(naive);
    const gatedFlips = countFlips(gated);
    note(`fist flips, bare cutoff  ${naiveFlips} over ${curls.length} frames`);
    note(`fist flips, gated        ${gatedFlips}`);
    expect(gatedFlips).toBeLessThan(naiveFlips / 4);
  });

  it('still commits to a deliberate close and open', () => {
    const gate = new FistGate();
    let t = 0;
    // Open for a while, then closed, then open again.
    for (let i = 0; i < 10; i++) gate.update(0.05, (t += SAMPLE_MS));
    expect(gate.isFist).toBe(false);
    for (let i = 0; i < 10; i++) gate.update(0.95, (t += SAMPLE_MS));
    expect(gate.isFist).toBe(true);
    for (let i = 0; i < 10; i++) gate.update(0.05, (t += SAMPLE_MS));
    expect(gate.isFist).toBe(false);
  });

  it('engages within a frame or two of a real close', () => {
    const gate = new FistGate();
    let t = 0;
    gate.update(0.05, t);
    let engagedAt = -1;
    for (let i = 1; i <= 10; i++) {
      t += SAMPLE_MS;
      if (gate.update(0.95, t) && engagedAt < 0) engagedAt = t;
    }
    note(`fist engage latency      ${engagedAt.toFixed(0)} ms`);
    expect(engagedAt).toBeGreaterThan(0);
    expect(engagedAt).toBeLessThanOrEqual(100);
  });
});

describe('slot assignment stability', () => {
  // Two wheel centers, side by side, as on a desktop layout.
  const anchors: Point[] = [{ x: 0.25, y: 0.6 }, { x: 0.75, y: 0.6 }];

  /** Stateless nearest-anchor assignment: what the tracker used to do. */
  function nearest(points: Point[]): number[] {
    const d = (p: Point, a: Point) => Math.hypot(p.x - a.x, p.y - a.y);
    if (points.length === 1) {
      return [d(points[0], anchors[0]) <= d(points[0], anchors[1]) ? 0 : 1];
    }
    const straight = d(points[0], anchors[0]) + d(points[1], anchors[1]);
    const swapped = d(points[0], anchors[1]) + d(points[1], anchors[0]);
    return straight <= swapped ? [0, 1] : [1, 0];
  }

  it('does not flip a lone hand back and forth across the seam', () => {
    // The realistic chatter case, and the one the stateless version actually
    // suffers from. A single raised hand resting midway between the two wheels
    // is equidistant, so landmark noise alone decides which one it drives, and
    // it re-decides every frame. On screen the marker teleports between wheels
    // several times a second while the hand is perfectly still.
    //
    // (Two hands held almost on top of each other is *not* tested as a win:
    // when the separation is smaller than the noise the two are genuinely
    // indistinguishable from position, and no amount of filtering recovers an
    // identity that the input does not contain.)
    const rng = mulberry32(23);
    const assigner = new SlotAssigner(2);
    const naive: number[] = [];
    const stable: number[] = [];

    for (let i = 0; i < 200; i++) {
      const p: Point = { x: 0.5 + gaussian(rng) * 0.010, y: 0.6 + gaussian(rng) * 0.010 };
      naive.push(nearest([p])[0]);
      stable.push(assigner.assign([p], anchors, i * SAMPLE_MS)[0]);
    }

    const naiveSwaps = countFlips(naive.map(v => v === 0));
    const stableSwaps = countFlips(stable.map(v => v === 0));
    note(`seam flips, stateless    ${naiveSwaps} over 200 frames`);
    note(`seam flips, hysteretic   ${stableSwaps}`);
    expect(naiveSwaps).toBeGreaterThan(20);
    expect(stableSwaps).toBeLessThanOrEqual(2);
  });

  it('moves a hand to the other slot once it commits to crossing', () => {
    const assigner = new SlotAssigner(2);
    // Settle on the left wheel.
    for (let i = 0; i < 20; i++) assigner.assign([{ x: 0.25, y: 0.6 }], anchors, i * SAMPLE_MS);
    // Then travel over to the right one and stay.
    let last = -1;
    for (let i = 20; i < 60; i++) {
      last = assigner.assign([{ x: 0.75, y: 0.6 }], anchors, i * SAMPLE_MS)[0];
    }
    expect(last).toBe(1);
  });

  it('still swaps when the hands genuinely cross over', () => {
    // Position remains the authority: this is the documented rule, and
    // hysteresis must delay a real crossing, never veto it.
    const assigner = new SlotAssigner(2);
    let last: number[] = [];
    for (let i = 0; i <= 60; i++) {
      const p = i / 60;
      // a travels left-to-right, b right-to-left, passing through each other.
      const a: Point = { x: 0.25 + 0.5 * p, y: 0.6 };
      const b: Point = { x: 0.75 - 0.5 * p, y: 0.6 };
      last = assigner.assign([a, b], anchors, i * SAMPLE_MS);
    }
    expect(last).toEqual([1, 0]);
  });

  it('assigns a lone first hand by position, with no history to drag it', () => {
    const assigner = new SlotAssigner(2);
    expect(assigner.assign([{ x: 0.8, y: 0.6 }], anchors, 0)).toEqual([1]);
    const fresh = new SlotAssigner(2);
    expect(fresh.assign([{ x: 0.2, y: 0.6 }], anchors, 0)).toEqual([0]);
  });

  it('forgets a slot once it has been empty long enough', () => {
    const assigner = new SlotAssigner(2);
    assigner.assign([{ x: 0.2, y: 0.6 }], anchors, 0);
    expect(assigner.remembered(0, 100)).not.toBeNull();
    expect(assigner.remembered(0, 5000)).toBeNull();
  });
});
